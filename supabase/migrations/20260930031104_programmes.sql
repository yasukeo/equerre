-- Maths programmes (DECISIONS.md, D-094).
--
-- A stream (« filière ») is what a student is in: 2e bac PC, SVT, STE… A programme is the maths
-- syllabus several streams share: PC, SVT, Agro, STE and STM all follow « 2e bac Sciences
-- expérimentales et technologiques ». Chapters, and so lessons and exercises, belong to the
-- programme, so each is written once; a student reads her stream's programme.
--
-- Adds the streams the brief left out (tronc commun technologique and lettres, 1re bac STE,
-- STM and lettres, 2e bac Agro, STE, STM, gestion comptable, lettres, sciences humaines) and
-- every chapter of the official programmes, by semester (supabase/curriculum/maths.json).
--
-- chapters.level_code is kept for now, nullable and no longer read: dropping it is left for
-- a later migration, once the owner has agreed.

create table public.programmes (
  code text primary key check (code ~ '^[0-9A-Z-]{2,16}$'),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  label text not null check (char_length(label) between 1 and 80),
  cycle text not null check (cycle in ('college', 'tronc_commun', '1bac', '2bac')),
  position smallint not null
);

alter table public.programmes enable row level security;

-- A table of contents, as chapters are; written by migrations only.
create policy "programmes: select everyone"
  on public.programmes for select to anon, authenticated
  using (true);

alter table public.levels
  add column programme_code text references public.programmes (code) on update cascade;

alter table public.chapters
  add column programme_code text references public.programmes (code) on update cascade,
  add column semester smallint check (semester in (1, 2)),
  add constraint chapters_programme_slug_key unique (programme_code, slug);

-- New chapters have no level: the column is no longer read.
alter table public.chapters alter column level_code drop not null;

