-- The programme a student reads: her stream's. Only while she is active or paused, as her
-- level was (D-060).
create function private.my_programme()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select l.programme_code
  from public.levels l
  where l.code = (select private.my_level());
$$;

-- « enrolled » lessons are her programme's, where they were her level's.
create or replace function private.lesson_visible_to_me(
  p_lesson_id uuid,
  p_chapter_id uuid,
  p_status public.publication_status,
  p_visibility public.lesson_visibility
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select
    (p_status = 'published' and p_visibility = 'public')
    or (select private.is_tutor())
    or (
      p_status = 'published'
      and p_visibility = 'enrolled'
      and exists (
        select 1
        from public.chapters c
        where c.id = p_chapter_id
          and c.programme_code = (select private.my_programme())
      )
    )
    or (
      p_status = 'published'
      and p_visibility = 'specific'
      and (select private.my_student_status()) in ('actif', 'en_pause')
      and exists (
        select 1
        from public.lesson_access la
        where la.lesson_id = p_lesson_id
          and la.student_id = (select auth.uid())
      )
    );
$function$;

